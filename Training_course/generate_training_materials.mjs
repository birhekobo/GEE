async function copyCover(course) {
  const relative = coverByTitle[course.title] || coverByPreview[course.preview];
  if (!relative) return null;
  const source = path.join(projectRoot, "public", "images", relative);
  const fileName = path.basename(relative);
  try {
    await access(source);
    await copyFile(source, path.join(coversDir, fileName));
    await copyFile(source, path.join(docsCoversDir, fileName));
    await copyFile(source, path.join(docsHtmlCoversDir, fileName));
    return fileName;
  } catch {
    return null;
  }
}

const usedSlugs = new Set();
const courses = [];
for (const [index, course] of trainingCourses.entries()) {
  let slug = slugify(course.title) || `course-${index + 1}`;
  while (usedSlugs.has(slug)) slug = `${slug}-${index + 1}`;
  usedSlugs.add(slug);
  const cover = await copyCover(course);
  const enriched = {
    ...course,
    slug,
    cover,
    accent: accents[index % accents.length],
    category: course.isFree ? "free" : "certificate",
    categoryLabel: course.isFree ? "Free Course" : "Certificate Course",
    feeLabel: formatCourseFee(course),
    totalFee: getEnrollmentTotal(course),
    moduleCount: course.contents.length,
  };
  enriched.document = buildCourseDocument(enriched);
  courses.push(enriched);
}

